import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const deployment = JSON.parse(await readFile(resolve(root, "deployments/monad-testnet.json"), "utf8"));
const names = ["AttestiaProfileRegistry", "ContributionRegistry", "AttestationRegistry"];
const contracts = {};

for (const name of names) {
  const artifact = JSON.parse(await readFile(resolve(root, `out/${name}.sol/${name}.json`), "utf8"));
  contracts[name] = { address: deployment.contracts[name].address, abi: artifact.abi };
  await mkdir(resolve(root, "apps/indexer/abis"), { recursive: true });
  await writeFile(resolve(root, `apps/indexer/abis/${name}.json`), JSON.stringify(artifact.abi, null, 2));
}

const output = `// Generated by scripts/export-web-contracts.mjs. Do not edit.\n` +
  `export const chainId = ${deployment.deployment.chainId} as const;\n` +
  `export const deploymentBlock = ${deployment.deployment.blockNumber}n;\n` +
  `export const contracts = ${JSON.stringify(contracts, null, 2)} as const;\n`;

await writeFile(resolve(root, "apps/web/lib/contracts.generated.ts"), output);
